import React, { useState, useEffect } from 'react';
import { fetchPatientReport, downloadPatientReportHtml } from '../api/client';
import LoadingSpinner from './Common/LoadingSpinner';

export default function ReportPanel({ selectedPatient, currentUser }) {
  const [report, setReport] = useState(null);
  const [isLoading, setIsLoading] = useState(true);
  const [errorMessage, setErrorMessage] = useState(null);
  const [isExporting, setIsExporting] = useState(false);
  const [exportError, setExportError] = useState(null);

  const patientId = selectedPatient?.id || currentUser?.patient_id;

  useEffect(() => {
    if (!patientId) {
      setIsLoading(false);
      return;
    }

    let isMounted = true;
    setIsLoading(true);
    setErrorMessage(null);
    setExportError(null);

    fetchPatientReport(patientId)
      .then((data) => {
        if (isMounted) setReport(data);
      })
      .catch((err) => {
        if (isMounted) {
          setErrorMessage(err.detail || err.message || 'Failed to generate comprehensive patient report.');
        }
      })
      .finally(() => {
        if (isMounted) setIsLoading(false);
      });

    return () => {
      isMounted = false;
    };
  }, [patientId]);

  const handlePrint = () => {
    window.print();
  };

  const handleDownloadHtml = async () => {
    if (!patientId || isExporting) return;
    setIsExporting(true);
    setExportError(null);
    try {
      const safePatientName = (report?.patient_name || `patient_${patientId}`)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '');
      const filename = `glucotwin_${safePatientName}_health_report.html`;
      await downloadPatientReportHtml(patientId, filename);
    } catch (err) {
      setExportError(err.detail || err.message || 'Failed to download report.');
    } finally {
      setIsExporting(false);
    }
  };

  if (!patientId) {
    return (
      <div className="section-container">
        <div className="empty-state-card">
          <p>Please select a patient to generate their clinical health report.</p>
        </div>
      </div>
    );
  }

  if (isLoading) {
    return (
      <div className="section-container" style={{ padding: '60px 0' }}>
        <LoadingSpinner message="Assembling multimodal telemetry, digital twin snapshot, and EHR records..." />
      </div>
    );
  }

  if (errorMessage) {
    return (
      <div className="section-container">
        <div className="report-error-card">
          <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
            <circle cx="12" cy="12" r="10" /><line x1="12" y1="8" x2="12" y2="12" /><line x1="12" y1="16" x2="12.01" y2="16" />
          </svg>
          <div>
            <h3>Report Generation Restrained</h3>
            <p>{errorMessage}</p>
          </div>
        </div>
      </div>
    );
  }

  if (!report) return null;

  return (
    <div className="section-container report-screen-container">
      {/* Report Action Bar */}
      <div className="report-action-header">
        <div>
          <span className="report-kicker-tag">Clinical &amp; Telemetry Report</span>
          <h2 className="report-main-title">
            Patient Health Summary — {report.patient_name}
          </h2>
          <p className="report-meta-line">
            Generated: {new Date(report.report_generated_at).toLocaleString()} | Generated by: {report.generated_by_username} ({report.generated_by_role})
          </p>
        </div>
        <div className="report-action-btns">
          <button type="button" className="report-action-btn secondary" onClick={handlePrint}>
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <polyline points="6 9 6 2 18 2 18 9" />
              <path d="M6 18H4a2 2 0 0 1-2-2v-5a2 2 0 0 1 2-2h16a2 2 0 0 1 2 2v5a2 2 0 0 1-2 2h-2" />
              <rect x="6" y="14" width="12" height="8" />
            </svg>
            Print Report
          </button>
          <button
            type="button"
            className="report-action-btn primary"
            onClick={handleDownloadHtml}
            disabled={isExporting}
          >
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4" />
              <polyline points="7 10 12 15 17 10" />
              <line x1="12" y1="15" x2="12" y2="3" />
            </svg>
            {isExporting ? 'Exporting...' : 'Export HTML Report'}
          </button>
        </div>
      </div>
      {exportError && (
        <div style={{ margin: '-10px 0 16px 0', padding: '10px 14px', borderRadius: '8px', background: 'rgba(239, 68, 68, 0.1)', color: '#ef4444', fontSize: '0.88rem', border: '1px solid rgba(239, 68, 68, 0.25)' }}>
          {exportError}
        </div>
      )}

      {/* Printable Report Document Card */}
      <div className="printable-report-sheet">
        {/* Document Header */}
        <div className="sheet-header">
          <div className="sheet-brand">
            <div className="sheet-logo">
              <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2">
                <path d="M22 12h-4l-3 9L9 3l-3 9H2" />
              </svg>
            </div>
            <div>
              <h3 className="sheet-title">GlucoTwin Comprehensive Health Record</h3>
              <span className="sheet-subtitle">Multimodal EHR, Sensor Telemetry &amp; Digital Twin Analytics</span>
            </div>
          </div>
          <div className="sheet-meta-box">
            <div>Patient ID: <strong>#{report.patient_id}</strong></div>
            <div>Report Date: <strong>{new Date(report.report_generated_at).toLocaleDateString()}</strong></div>
            <div>Security Scope: <strong>RBAC Verified</strong></div>
          </div>
        </div>

        {/* Section 1: Demographics */}
        <div className="sheet-section">
          <h4 className="sheet-section-title">Patient Profile &amp; Clinical Demographics</h4>
          <div className="sheet-demographics-grid">
            <div className="sheet-kv"><span className="kv-label">Full Name:</span><span className="kv-val">{report.patient_name}</span></div>
            <div className="sheet-kv"><span className="kv-label">Age / Gender:</span><span className="kv-val">{report.age} yrs / {report.gender}</span></div>
            <div className="sheet-kv"><span className="kv-label">Diabetes Type:</span><span className="kv-val">{report.diabetes_type}</span></div>
            <div className="sheet-kv"><span className="kv-label">Years Diagnosed:</span><span className="kv-val">{report.years_since_diagnosis} yrs</span></div>
            <div className="sheet-kv"><span className="kv-label">Calculated BMI:</span><span className="kv-val">{report.calculated_bmi ? `${report.calculated_bmi} kg/m²` : 'Not recorded'}</span></div>
            <div className="sheet-kv"><span className="kv-label">Historical Diagnoses:</span><span className="kv-val">{report.historical_diagnoses || 'None'}</span></div>
          </div>
          {report.medical_history && (
            <div className="sheet-notes-callout">
              <strong>Clinical History Notes:</strong> {report.medical_history}
            </div>
          )}
        </div>

        {/* Section 2: Glycemic & Vitals Summary */}
        <div className="sheet-grid-2">
          <div className="sheet-section">
            <h4 className="sheet-section-title">Glycemic Telemetry Metrics</h4>
            <div className="sheet-stat-list">
              <div className="sheet-stat-row">
                <span>Latest Glucose</span>
                <strong>{report.latest_glucose_mg_dl ? `${report.latest_glucose_mg_dl} mg/dL` : 'No readings'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Time-in-Range (70-180 mg/dL)</span>
                <strong className="text-emerald">{report.time_in_range_pct !== null ? `${report.time_in_range_pct}%` : 'N/A'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Time-Above-Range (&gt;180 mg/dL)</span>
                <strong className="text-amber">{report.time_above_range_pct !== null ? `${report.time_above_range_pct}%` : 'N/A'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Time-Below-Range (&lt;70 mg/dL)</span>
                <strong className="text-rose">{report.time_below_range_pct !== null ? `${report.time_below_range_pct}%` : 'N/A'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>1-Hour Rolling Average</span>
                <strong>{report.rolling_avg_glucose_1h ? `${report.rolling_avg_glucose_1h} mg/dL` : 'N/A'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>1-Hour Variability (StdDev)</span>
                <strong>{report.glucose_variability_std_1h ? `±${report.glucose_variability_std_1h} mg/dL` : 'N/A'}</strong>
              </div>
            </div>
          </div>

          <div className="sheet-section">
            <h4 className="sheet-section-title">Autonomic &amp; Digital Twin Status</h4>
            <div className="sheet-stat-list">
              <div className="sheet-stat-row">
                <span>Latest Heart Rate</span>
                <strong>{report.latest_heart_rate_bpm ? `${report.latest_heart_rate_bpm} bpm` : 'No readings'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Heart Rate Variability (RMSSD)</span>
                <strong>{report.latest_hrv_ms ? `${report.latest_hrv_ms} ms` : 'No readings'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>1-Hour Average Heart Rate</span>
                <strong>{report.avg_heart_rate_1h ? `${report.avg_heart_rate_1h} bpm` : 'N/A'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Digital Twin Status</span>
                <strong className={`twin-pill ${report.twin_status}`}>
                  {report.twin_status.toUpperCase()}
                </strong>
              </div>
              <div className="sheet-stat-row">
                <span>Twin Glycemic Risk Score</span>
                <strong>{report.twin_risk_score !== null ? `${Math.round(report.twin_risk_score * 100)}%` : '0%'}</strong>
              </div>
              <div className="sheet-stat-row">
                <span>Active Risk Alerts</span>
                <strong>{report.active_alerts_count} active</strong>
              </div>
            </div>
          </div>
        </div>

        {/* Section 3: Laboratory Panels */}
        <div className="sheet-section">
          <h4 className="sheet-section-title">Laboratory Panels (EHR Panels)</h4>
          {report.lab_panels && report.lab_panels.length > 0 ? (
            <div className="sheet-table-wrapper">
              <table className="sheet-table">
                <thead>
                  <tr>
                    <th>Test Name</th>
                    <th>Result</th>
                    <th>Reference Range</th>
                    <th>Collection Date</th>
                    <th>Laboratory Source</th>
                  </tr>
                </thead>
                <tbody>
                  {report.lab_panels.map((lab) => (
                    <tr key={lab.id}>
                      <td><strong>{lab.test_name}</strong></td>
                      <td>{lab.result} {lab.unit}</td>
                      <td>{lab.reference_range || 'N/A'}</td>
                      <td>{new Date(lab.measurement_date).toLocaleDateString()}</td>
                      <td>{lab.lab_source || 'Simulated Lab'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ) : (
            <p className="sheet-empty-text">No structured laboratory panels recorded on file.</p>
          )}
        </div>

        {/* Section 4: Experimental Predictions & Explainability */}
        <div className="sheet-section">
          <h4 className="sheet-section-title">Experimental Predictive Intelligence &amp; XAI</h4>
          <div className="sheet-demographics-grid">
            <div className="sheet-kv">
              <span className="kv-label">Spike Prediction Status:</span>
              <span className="kv-val">
                {report.experimental_spike_predicted !== null
                  ? (report.experimental_spike_predicted ? 'Spike Projected (≥180 mg/dL in 2h)' : 'Normal Projection')
                  : 'Insufficient data'}
              </span>
            </div>
            <div className="sheet-kv">
              <span className="kv-label">Projected Spike Risk Score:</span>
              <span className="kv-val">
                {report.experimental_spike_risk_score !== null
                  ? `${Math.round(report.experimental_spike_risk_score * 100)}%`
                  : 'N/A'}
              </span>
            </div>
            <div className="sheet-kv">
              <span className="kv-label">Inference Model Version:</span>
              <span className="kv-val">{report.experimental_model_version || '1.0.0-synthetic-rf'}</span>
            </div>
          </div>

          {report.top_feature_contributions && Object.keys(report.top_feature_contributions).length > 0 && (
            <div style={{ marginTop: '14px' }}>
              <span className="sheet-subheading">Key Telemetry Feature Contributions:</span>
              <div className="sheet-feature-chips">
                {Object.entries(report.top_feature_contributions).slice(0, 6).map(([feat, val]) => (
                  <div key={feat} className="sheet-feature-chip">
                    <span className="feat-name">{feat.replace(/_/g, ' ')}</span>
                    <span className="feat-val">{(val * 100).toFixed(1)}%</span>
                  </div>
                ))}
              </div>
            </div>
          )}

          {report.data_quality_warnings && report.data_quality_warnings.length > 0 && (
            <div className="sheet-warnings-list">
              {report.data_quality_warnings.map((w, idx) => (
                <div key={idx} className="sheet-warning-item">
                  <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                    <path d="M10.29 3.86L1.82 18a2 2 0 0 0 1.71 3h16.94a2 2 0 0 0 1.71-3L13.71 3.86a2 2 0 0 0-3.42 0z" />
                    <line x1="12" y1="9" x2="12" y2="13" /><line x1="12" y1="17" x2="12.01" y2="17" />
                  </svg>
                  <span>{w}</span>
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Section 5: Data Streams & Audit */}
        <div className="sheet-data-streams">
          <span><strong>Data Ingestion Streams:</strong> {report.data_sources.join(', ')}</span>
        </div>

        {/* Mandatory Research Prototype Disclaimer */}
        <div className="sheet-legal-disclaimer">
          <strong>RESEARCH &amp; DEMONSTRATION PROTOTYPE ONLY:</strong>
          <p>{report.disclaimer}</p>
        </div>
      </div>
    </div>
  );
}
