"""
routers/reports.py - Patient Comprehensive Clinical & Digital Twin Report Generation
=====================================================================================

Provides endpoints for patient-specific health summary and digital twin reports:
  GET  /api/reports/patient/{patient_id}        -> Structured JSON report
  GET  /api/reports/patient/{patient_id}/export -> Formatted standalone printable HTML report

Security & Patient Isolation:
  - A clinician may generate reports only for authorized patients within their scope.
  - A patient may generate or download only their own report.
  - Cross-patient requests are blocked with HTTP 403 Forbidden.
  - Missing values are explicitly labeled; no synthetic values or diagnoses are invented.
  - Prominent synthetic data and research-prototype disclaimers are enforced.
"""

