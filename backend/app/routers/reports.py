router = APIRouter(prefix="/api/reports", tags=["Reports"])

REPORT_DISCLAIMER = (
    "RESEARCH & DEMONSTRATION PROTOTYPE ONLY: This comprehensive patient health report is "
    "generated by GlucoTwin for research, testing, and demonstration purposes. All patient profiles, "
    "continuous glucose monitoring (CGM) telemetry, autonomic vitals, and laboratory panels are "
    "synthetic demonstration data. Glucose-spike predictions, digital twin state vectors, and risk "
    "scores are experimental machine-learning/heuristic calculations and DO NOT constitute a medical "
    "diagnosis, clinical certification, or prescription. Healthcare professionals must independently "
    "evaluate clinical evidence before taking any clinical actions."
)


def _build_patient_report(patient_id: int, current_user: User, db: Session) -> PatientReportResponse:
    """Core builder assembling structured patient report data."""
    check_patient_authorization(patient_id, current_user, db)

    patient = db.query(Patient).filter(Patient.id == patient_id).first()
    if not patient:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Patient #{patient_id} not found."
        )

    # 1. Glycemic trends & metrics
    glucose_readings = (
        db.query(GlucoseReading)
        .filter(GlucoseReading.patient_id == patient_id, GlucoseReading.is_valid == True)
        .order_by(GlucoseReading.timestamp.desc())
        .all()
    )

    latest_g = glucose_readings[0] if glucose_readings else None
    latest_g_val = float(latest_g.value) if latest_g else None
    latest_g_ts = latest_g.timestamp if latest_g else None

    tir_pct = None
    tar_pct = None
    tbr_pct = None
    avg_1h = None
    avg_3h = None
    std_1h = None
    g_status = "No glucose readings recorded" if not glucose_readings else "Telemetry Active"

    data_sources_set = set()
    earliest_ts = None
    latest_ts = None

    if glucose_readings:
        data_sources_set.add("Continuous Glucose Telemetry (Synthetic)")
        vals = [r.value for r in glucose_readings]
        total_r = len(vals)
        in_range = sum(1 for v in vals if 70.0 <= v <= 180.0)
        above_range = sum(1 for v in vals if v > 180.0)
        below_range = sum(1 for v in vals if v < 70.0)

        tir_pct = round((in_range / total_r) * 100.0, 1)
        tar_pct = round((above_range / total_r) * 100.0, 1)
        tbr_pct = round((below_range / total_r) * 100.0, 1)

        # 1-hour window from latest reading
        ref_ts = latest_g.timestamp
        readings_1h = [r.value for r in glucose_readings if (ref_ts - r.timestamp).total_seconds() <= 3600]
        readings_3h = [r.value for r in glucose_readings if (ref_ts - r.timestamp).total_seconds() <= 10800]

        if readings_1h:
            avg_1h = round(float(np.mean(readings_1h)), 1)
            std_1h = round(float(np.std(readings_1h)), 1)
        if readings_3h:
            avg_3h = round(float(np.mean(readings_3h)), 1)

        earliest_ts = glucose_readings[-1].timestamp
        latest_ts = glucose_readings[0].timestamp

    # 2. Vital signs
    vitals = (
        db.query(VitalReading)
        .filter(VitalReading.patient_id == patient_id)
        .order_by(VitalReading.timestamp.desc())
        .all()
    )

    latest_v = vitals[0] if vitals else None
    latest_hr = float(latest_v.heart_rate) if latest_v and latest_v.heart_rate else None
    latest_hrv = float(latest_v.hrv) if latest_v and latest_v.hrv else None
    avg_hr_1h = None
    avg_hrv_1h = None
    v_status = "No vital readings recorded" if not vitals else "Telemetry Active"

    if vitals:
        data_sources_set.add("Autonomic PPG/ECG Sensor Telemetry (Synthetic)")
        ref_v_ts = latest_v.timestamp
        v_1h = [v for v in vitals if (ref_v_ts - v.timestamp).total_seconds() <= 3600]
        hrs_1h = [v.heart_rate for v in v_1h if v.heart_rate is not None]
        hrvs_1h = [v.hrv for v in v_1h if v.hrv is not None]
        if hrs_1h:
            avg_hr_1h = round(float(np.mean(hrs_1h)), 1)
        if hrvs_1h:
            avg_hrv_1h = round(float(np.mean(hrvs_1h)), 1)

        if earliest_ts is None or vitals[-1].timestamp < earliest_ts:
            earliest_ts = vitals[-1].timestamp
        if latest_ts is None or vitals[0].timestamp > latest_ts:
            latest_ts = vitals[0].timestamp

    # 3. Lab Results
    labs = (
        db.query(LabResult)
        .filter(LabResult.patient_id == patient_id)
        .order_by(LabResult.measurement_date.desc())
        .all()
    )
    if labs:
        data_sources_set.add("Laboratory Panel History (Synthetic EHR)")

    # 4. Genetic Markers
    genetics = (
        db.query(GeneticMarker)
        .filter(GeneticMarker.patient_id == patient_id)
        .order_by(GeneticMarker.id.asc())
        .all()
    )
    if genetics:
        data_sources_set.add("Genomic Susceptibility Panel (Synthetic)")

    # 5. Digital Twin state & Alerts
    twin_state = (
        db.query(DigitalTwinState)
        .filter(DigitalTwinState.patient_id == patient_id)
        .order_by(DigitalTwinState.timestamp.desc())
        .first()
    )
    twin_status = twin_state.status if twin_state and twin_state.status else "normal"
    twin_risk = round(float(twin_state.risk_score), 2) if twin_state and twin_state.risk_score else 0.0

    alerts = (
        db.query(Alert)
        .filter(Alert.patient_id == patient_id)
        .order_by(Alert.timestamp.desc())
        .all()
    )
    active_alerts = [a for a in alerts if a.status == "active" or (a.status is None and not a.acknowledged)]
    recent_alerts_read = [
        AlertRead(
            id=a.id,
            patient_id=a.patient_id,
            patient_name=patient.name,
            timestamp=a.timestamp,
            severity=a.severity,
            message=a.message,
            alert_type=a.alert_type,
            source=a.source or "observed_reading",
            status=a.status or "active",
            trigger_value=a.trigger_value,
            threshold=a.threshold,
            acknowledged=bool(a.acknowledged),
            acknowledged_at=a.acknowledged_at,
            resolved_at=a.resolved_at,
            dedup_key=a.dedup_key,
        )
        for a in alerts[:5]
    ]

    # 6. Experimental Prediction
    spike_pred = None
    spike_score = None
    model_version = None
    top_features = {}
    quality_warnings = []

    if glucose_readings and len(glucose_readings) >= 2:
        try:
            from app.routers.predictions import ML_ARTIFACT_DIR
            pipeline, metadata = load_model_artifact(ML_ARTIFACT_DIR)
            if pipeline and metadata:
                model_version = metadata.get("model_version", "1.0.0-synthetic-rf")
                p_dict = {
                    "id": patient.id,
                    "name": patient.name,
                    "age": patient.age,
                    "gender": patient.gender,
                    "diabetes_type": patient.diabetes_type,
                    "years_since_diagnosis": patient.years_since_diagnosis,
                }
                as_of = latest_g.timestamp
                features_dict, warnings = extract_features_at_timestamp(
                    patient_dict=p_dict,
                    glucose_readings=glucose_readings,
                    vital_readings=vitals,
                    as_of_timestamp=as_of,
                )
                quality_warnings = warnings
                feature_vector = np.array([[features_dict[col] for col in FEATURE_NAMES]], dtype=np.float32)
                proba = float(pipeline.predict_proba(feature_vector)[0, 1])
                spike_score = round(proba, 3)
                spike_pred = bool(proba >= 0.5)

                # Feature contributions
                if hasattr(pipeline.named_steps["classifier"], "feature_importances_"):
                    importances = pipeline.named_steps["classifier"].feature_importances_
                    for idx, name in enumerate(FEATURE_NAMES):
                        top_features[name] = round(float(importances[idx]), 3)
        except Exception:
            quality_warnings.append("Prediction engine temporarily offline during report compilation.")
    else:
        quality_warnings.append("Insufficient time-series history for forward predictive inference.")

    data_sources_list = sorted(list(data_sources_set)) or ["Synthetic Patient Profile"]

    return PatientReportResponse(
        patient_id=patient.id,
        patient_name=patient.name,
        age=patient.age,
        gender=patient.gender,
        diabetes_type=patient.diabetes_type,
        years_since_diagnosis=patient.years_since_diagnosis,
        calculated_bmi=patient.calculated_bmi,
        historical_diagnoses=patient.historical_diagnoses or "None documented",
        medical_history=patient.medical_history or "None documented",
        report_generated_at=datetime.now(timezone.utc),
        generated_by_username=current_user.username,
        generated_by_role=current_user.role,
        latest_glucose_mg_dl=latest_g_val,
        latest_glucose_timestamp=latest_g_ts,
        time_in_range_pct=tir_pct,
        time_above_range_pct=tar_pct,
        time_below_range_pct=tbr_pct,
        rolling_avg_glucose_1h=avg_1h,
        rolling_avg_glucose_3h=avg_3h,
        glucose_variability_std_1h=std_1h,
        glucose_status_label=g_status,
        latest_heart_rate_bpm=latest_hr,
        latest_hrv_ms=latest_hrv,
        avg_heart_rate_1h=avg_hr_1h,
        avg_hrv_1h=avg_hrv_1h,
        vitals_status_label=v_status,
        lab_panels=[LabResultRead.model_validate(l) for l in labs],
        genetic_markers=[GeneticMarkerRead.model_validate(g) for g in genetics],
        twin_status=twin_status,
        twin_risk_score=twin_risk,
        active_alerts_count=len(active_alerts),
        recent_alerts=recent_alerts_read,
        experimental_spike_predicted=spike_pred,
        experimental_spike_risk_score=spike_score,
        experimental_model_version=model_version,
        top_feature_contributions=top_features,
        data_quality_warnings=quality_warnings,
        data_sources=data_sources_list,
        earliest_telemetry_timestamp=earliest_ts,
        latest_telemetry_timestamp=latest_ts,
        is_synthetic_data=True,
        disclaimer=REPORT_DISCLAIMER,
    )


@router.get("/patient/{patient_id}", response_model=PatientReportResponse)
def get_patient_report(
    patient_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Generate and return structured comprehensive health report for a patient.
    - Verified clinicians view reports for patients within their permitted care scope.
    - Patients view only their own report.
    - Cross-patient requests are blocked with HTTP 403 Forbidden.
    """
    return _build_patient_report(patient_id, current_user, db)


